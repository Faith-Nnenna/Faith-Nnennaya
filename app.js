  if(!projectForm.reportValidity())return;
  const draft=projectEmail();showEmailDraft(draft);
  try{await navigator.clipboard.writeText('To: orjinnennafaith@gmail.com\nSubject: '+draft.subject+'\n\n'+draft.body);formStatus.textContent='Message copied. Paste it into an email to orjinnennafaith@gmail.com.';}
